"""per-harness-agent-tools: each harness gets only its own tool names.

Claude Code reads `plugins/gauntlet/agents/*.md` (`tools:` holds Claude Code names).
pi-subagents reads `plugins/gauntlet/pi-agents/*.md`, generated by
`scripts/build_pi_agents.py` from the `pi-*` keys of the same source files.
"""

import glob
import os
import subprocess
import sys
import tempfile
import unittest

import helpers

AGENTS_DIR = os.path.join(helpers.PLUGIN, "agents")
PI_AGENTS_DIR = os.path.join(helpers.PLUGIN, "pi-agents")
BUILD = os.path.join(helpers.REPO_ROOT, "scripts", "build_pi_agents.py")
ROLES = ("alpha", "beta", "gamma", "delta", "epsilon", "eta", "zeta")

# pi-subagents: pi built-ins, the nested `subagent` tool, and direct MCP selections of the gauntlet server.
PI_BUILTINS = {"read", "bash", "edit", "write", "grep", "find", "ls", "subagent"}
PI_READ_ONLY = {"read", "grep", "find", "ls"}
PI_MCP_PREFIX = "mcp:gauntlet/"

# Claude Code tool names (https://code.claude.com/docs/en/sub-agents#available-tools) and the plugin's MCP tools.
CLAUDE_TOOLS = {
    "Agent", "Bash", "Edit", "Glob", "Grep", "NotebookEdit", "Read", "SendMessage",
    "Skill", "TodoWrite", "WebFetch", "WebSearch", "Write",
}
CLAUDE_MCP_PREFIX = "mcp__plugin_gauntlet_gauntlet__"
CLAUDE_READ_ONLY = {"Read", "Glob", "Grep", "Skill", "WebFetch", "WebSearch"}


def split(value):
    return [t.strip() for t in value.split(",") if t.strip()]


def claude_tools(name):
    meta = helpers.read_frontmatter(os.path.join(AGENTS_DIR, name + ".md"))
    return None if "tools" not in meta else split(meta["tools"])


def pi_tools(name):
    meta = helpers.read_frontmatter(os.path.join(PI_AGENTS_DIR, name + ".md"))
    return None if "tools" not in meta else split(meta["tools"])


def server_tools():
    return set(helpers.load_server().TOOLS)


def is_pi_name(tool):
    if tool.startswith(PI_MCP_PREFIX):
        return tool[len(PI_MCP_PREFIX):] in server_tools()
    return tool in PI_BUILTINS


def is_claude_name(tool):
    if tool.startswith(CLAUDE_MCP_PREFIX):
        return tool[len(CLAUDE_MCP_PREFIX):] in server_tools()
    return tool in CLAUDE_TOOLS


class MixedListDetectionTest(unittest.TestCase):
    def test_the_old_mixed_list_is_rejected_on_both_harnesses(self):
        mixed = split("Read, Glob, Grep, Skill, WebFetch, WebSearch, read, grep, find, ls")
        self.assertEqual([t for t in mixed if not is_pi_name(t)], ["Read", "Glob", "Grep", "Skill", "WebFetch", "WebSearch"])
        self.assertEqual([t for t in mixed if not is_claude_name(t)], ["read", "grep", "find", "ls"])


class ClaudeListsTest(unittest.TestCase):
    def test_claude_lists_hold_only_claude_names(self):
        for name in ROLES:
            tools = claude_tools(name)
            if tools is None:
                continue
            with self.subTest(agent=name):
                self.assertEqual([t for t in tools if not is_claude_name(t)], [])

    def test_read_only_roles_are_read_only_on_claude(self):
        for name in ("eta", "zeta"):
            with self.subTest(agent=name):
                self.assertTrue(set(claude_tools(name) or ["missing"]) <= CLAUDE_READ_ONLY, claude_tools(name))


class PiListsTest(unittest.TestCase):
    def test_every_role_has_a_pi_variant(self):
        self.assertEqual(
            sorted(os.path.basename(p)[:-3] for p in glob.glob(os.path.join(PI_AGENTS_DIR, "*.md"))),
            sorted(ROLES),
        )

    def test_pi_lists_hold_only_pi_names(self):
        for name in ROLES:
            tools = pi_tools(name)
            if tools is None:
                continue
            with self.subTest(agent=name):
                self.assertEqual([t for t in tools if not is_pi_name(t)], [])

    def test_a_pi_list_exists_exactly_where_a_claude_list_does(self):
        for name in ROLES:
            with self.subTest(agent=name):
                self.assertEqual(pi_tools(name) is None, claude_tools(name) is None)

    def test_read_only_roles_are_read_only_on_pi(self):
        for name in ("eta", "zeta"):
            with self.subTest(agent=name):
                self.assertEqual(set(pi_tools(name) or []), PI_READ_ONLY)

    def test_epsilon_gets_every_gauntlet_server_tool_on_pi(self):
        named = {t[len(PI_MCP_PREFIX):] for t in pi_tools("epsilon") or [] if t.startswith(PI_MCP_PREFIX)}
        self.assertEqual(named, server_tools())

    def test_epsilon_runs_in_the_background_on_pi_so_the_mcp_adapter_loads(self):
        meta = helpers.read_frontmatter(os.path.join(PI_AGENTS_DIR, "epsilon.md"))
        self.assertEqual(meta.get("async"), "true")

    def test_roles_that_start_agents_get_subagent_on_pi(self):
        for name in ROLES:
            tools = claude_tools(name)
            if tools is None:
                continue
            with self.subTest(agent=name):
                self.assertEqual("subagent" in (pi_tools(name) or []), "Agent" in tools)

    def test_pi_variants_carry_no_claude_only_or_source_keys(self):
        for name in ROLES:
            meta = helpers.read_frontmatter(os.path.join(PI_AGENTS_DIR, name + ".md"))
            with self.subTest(agent=name):
                self.assertEqual([k for k in meta if k.startswith("pi-")], [])


class GeneratedFilesTest(unittest.TestCase):
    def test_pi_variants_are_up_to_date_with_the_sources(self):
        result = subprocess.run([sys.executable, BUILD, "--check"], capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_build_renames_pi_keys_and_keeps_the_body(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, out = os.path.join(tmp, "src"), os.path.join(tmp, "out")
            os.makedirs(src)
            with open(os.path.join(src, "x.md"), "w", encoding="utf-8") as f:
                f.write("---\nname: x\ndescription: d\ntools: Read, Glob\npi-tools: read, find, ls\npi-async: true\n---\n\nBody.\n")
            subprocess.run([sys.executable, BUILD, "--src", src, "--out", out], check=True)
            with open(os.path.join(out, "x.md"), encoding="utf-8") as f:
                generated = f.read()
            self.assertIn("---\nname: x\ndescription: d\ntools: read, find, ls\nasync: true\n---\n\nBody.\n", generated)
            self.assertNotIn("Read", generated)

    def test_check_fails_on_a_stale_variant(self):
        with tempfile.TemporaryDirectory() as tmp:
            src, out = os.path.join(tmp, "src"), os.path.join(tmp, "out")
            os.makedirs(src)
            os.makedirs(out)
            with open(os.path.join(src, "x.md"), "w", encoding="utf-8") as f:
                f.write("---\nname: x\ntools: Read\npi-tools: read\n---\nBody.\n")
            with open(os.path.join(out, "x.md"), "w", encoding="utf-8") as f:
                f.write("---\nname: x\ntools: Read, read\n---\nBody.\n")
            result = subprocess.run([sys.executable, BUILD, "--src", src, "--out", out, "--check"], capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("x.md", result.stdout + result.stderr)


if __name__ == "__main__":
    unittest.main()
